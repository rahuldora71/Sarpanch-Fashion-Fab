package com.sff.authapp.login.controllers;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.sff.authapp.login.dtos.whatsapp.WhatsAppWebhookDtos.WhatsAppWebhookPayloadDto;
import com.sff.authapp.login.security.WhatsAppSignatureValidator;
import com.sff.authapp.login.services.WhatsAppWebhookService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.Map;

/**
 * Controller providing the official Meta WhatsApp Cloud API Webhook endpoints.
 * <p>
 * Supports:
 * - GET /api/whatsapp/webhook: Meta Webhook verification handshake with hub.mode, hub.verify_token, and hub.challenge
 * - POST /api/whatsapp/webhook: Secure event ingestion with HMAC-SHA256 signature verification via X-Hub-Signature-256
 */
@RestController
@RequestMapping("/api/whatsapp")
@RequiredArgsConstructor
@Slf4j
@Tag(
        name = "Meta WhatsApp Webhook",
        description = "Publicly exposed endpoints for Meta WhatsApp Business Platform webhook verification and event delivery"
)
public class WhatsAppWebhookController {

    private static final int MAX_PAYLOAD_BYTES = 4 * 1024 * 1024; // 4MB safety limit (Meta max is 3MB)

    private final WhatsAppWebhookService webhookService;
    private final WhatsAppSignatureValidator signatureValidator;
    private final ObjectMapper objectMapper;

    /**
     * Webhook Verification Endpoint (GET).
     * <p>
     * Meta sends a GET request when configuring the webhook URL in the Meta Developer App Dashboard.
     * Must return the hub.challenge value as plain text with HTTP 200 when verification token matches.
     */
    @GetMapping(value = "/webhook", produces = MediaType.TEXT_PLAIN_VALUE)
    @Operation(
            summary = "Meta Webhook Verification Handshake",
            description = "Validates the verification token sent by Meta and echoes back the hub.challenge."
    )
    public ResponseEntity<String> verifyWebhook(
            @Parameter(description = "Mode sent by Meta, expected to be 'subscribe'")
            @RequestParam(name = "hub.mode", required = false) String mode,

            @Parameter(description = "Verification token configured in Meta App Dashboard")
            @RequestParam(name = "hub.verify_token", required = false) String verifyToken,

            @Parameter(description = "Random challenge string generated by Meta to echo back")
            @RequestParam(name = "hub.challenge", required = false) String challenge
    ) {
        if (challenge == null || challenge.isBlank()) {
            log.warn("Rejected WhatsApp webhook verification: missing hub.challenge parameter");
            return ResponseEntity.status(HttpStatus.FORBIDDEN).body("Missing challenge");
        }

        boolean verified = webhookService.verifyWebhookToken(mode, verifyToken);

        if (verified) {
            log.info("Meta WhatsApp webhook verification handshake succeeded.");
            return ResponseEntity.ok(challenge);
        } else {
            log.warn("Meta WhatsApp webhook verification failed (token or mode mismatch).");
            return ResponseEntity.status(HttpStatus.FORBIDDEN).body("Verification failed");
        }
    }

    /**
     * Webhook Event Delivery Endpoint (POST).
     * <p>
     * Meta sends events (message status updates and incoming customer messages) via POST.
     * The request body is cryptographically verified against the X-Hub-Signature-256 header.
     */
    @PostMapping("/webhook")
    @Operation(
            summary = "Receive Meta WhatsApp Webhook Notifications",
            description = "Ingests WhatsApp Cloud API events (sent/delivered/read/failed statuses and incoming messages) after HMAC-SHA256 signature verification."
    )
    public ResponseEntity<Map<String, String>> receiveWebhook(
            @RequestHeader(name = "X-Hub-Signature-256", required = false) String signatureHeader,
            @RequestBody(required = false) byte[] rawPayload
    ) {
        // 1. Guard against empty request body
        if (rawPayload == null || rawPayload.length == 0) {
            log.warn("Rejected WhatsApp webhook: empty request body");
            return ResponseEntity.status(HttpStatus.BAD_REQUEST).body(Map.of("error", "Empty body"));
        }

        // 2. Guard against oversized request bodies
        if (rawPayload.length > MAX_PAYLOAD_BYTES) {
            log.warn("Rejected WhatsApp webhook: payload size ({}) exceeds maximum limit ({} bytes)",
                    rawPayload.length, MAX_PAYLOAD_BYTES);
            return ResponseEntity.status(HttpStatus.PAYLOAD_TOO_LARGE).body(Map.of("error", "Payload too large"));
        }

        // 3. Verify HMAC-SHA256 signature against Meta App Secret
        if (!signatureValidator.isValidSignature(rawPayload, signatureHeader)) {
            log.warn("Rejected WhatsApp webhook: invalid or missing X-Hub-Signature-256 signature header");
            return ResponseEntity.status(HttpStatus.UNAUTHORIZED).body(Map.of("error", "Invalid signature"));
        }

        // 4. Safely parse JSON into typed DTO
        WhatsAppWebhookPayloadDto payload;
        try {
            payload = objectMapper.readValue(rawPayload, WhatsAppWebhookPayloadDto.class);
        } catch (Exception ex) {
            log.warn("Rejected WhatsApp webhook: malformed JSON payload ({})", ex.getMessage());
            return ResponseEntity.status(HttpStatus.BAD_REQUEST).body(Map.of("error", "Malformed JSON"));
        }

        // 5. Ingest and process events durably and idempotently
        webhookService.processWebhookPayload(payload, rawPayload);

        // 6. Fast acknowledgement to Meta
        return ResponseEntity.ok(Map.of("status", "EVENT_RECEIVED"));
    }
}
